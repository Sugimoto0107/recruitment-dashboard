export function categorizeJobCode(code: string): JobCodeCategory {
  const exact = EXACT_MAP[code];
  if (exact) return exact;
  for (const [re, category] of KEYWORD_RULES) {
    if (re.test(code)) return category;
  }
  return "その他";
}

export interface JobCodeCategoryGroup {
  category: JobCodeCategory;
  total: number;
  items: [string, number][];
}

// 職種コード別件数を doda カテゴリごとにグループ化（件数0は除外、空カテゴリは非表示）
export function groupJobCodesByCategory(
  byJobCode: Record<string, number>
): JobCodeCategoryGroup[] {
  const map = new Map<JobCodeCategory, [string, number][]>();
  for (const [code, count] of Object.entries(byJobCode)) {
    if (count <= 0) continue;
    const category = categorizeJobCode(code);
    if (!map.has(category)) map.set(category, []);
    map.get(category)!.push([code, count]);
  }
  return JOB_CODE_CATEGORIES.filter((c) => map.has(c)).map((category) => {
    const items = map.get(category)!.sort((a, b) => b[1] - a[1]);
    return {
      category,
      total: items.reduce((s, [, n]) => s + n, 0),
      items,
    };
  });
}
